if 'page' not in st.session_state:
    st.session_state.page='start'
if st.session_state.page == 'start':
    st.title('Главное меню')
    if st.button('Начать тест'):
        st.session_state.page='test'
        st.rerun()   

elif st.session_state.page == 'test':
     
    if 'all' not in st.session_state:
        st.session_state.all=0
        st.session_state.test_q=random.sample(questions,len(questions))

    if 'cor' not in st.session_state:
        st.session_state.cor=0

    if 'is_answered' not in st.session_state:
        st.session_state.is_answered = False

    if st.button('Выйти'):
        st.session_state.page='results'
        st.rerun()

    q=st.session_state.test_q[st.session_state.all]
    st.subheader('Вопрос:')
    st.info(q['q'])
    st.write('*Выбери верные утверждения:*')
    u_choices=[]

    for option in q['options']:
        opt_num=option[0]
        if st.checkbox(option, key=f'{st.session_state.all}_{opt_num}'):
            u_choices.append(opt_num)
    if not st.session_state.is_answered:
        if st.button('Ответить'):
            u_choices.sort()
            correct_answers=q['answer']
            correct_answers.sort()

            if u_choices == correct_answers:
                st.session_state.feedback='Правильно, молодец!'
                st.session_state.cor+=1
            else:
                st.session_state.feedback=(f'Неверно! Правильный ответ: {','.join(correct_answers)}')

            st.session_state.is_answered=True
            st.rerun()
    else:
        if 'feedback' in st.session_state:
            if 'Правильно, молодец!' in st.session_state.feedback:
                st.success(st.session_state.feedback)
                st.balloons()
            else:
                st.error(st.session_state.feedback)
                
        if st.button('Следующий вопрос'):
            st.session_state.all+=1
            st.session_state.is_answered=False
            del st.session_state.feedback
            st.rerun()
elif st.session_state.page == 'results':
    st.title('Результаты')
    st.write('*Ты завершил тест!*')
    st.success(f'Твой результат: {st.session_state.cor}/{st.session_state.all}')

    


